  fn record;
  total integer := 0;
  denied integer := 0;
  leaked text := '';
begin
  for fn in
    select format('%I.%I(%s)', namespace.nspname, procedure.proname,
             coalesce((select pg_catalog.string_agg('null::' || pg_catalog.format_type(arg.oid, null), ', ' order by arg.ord)
                       from pg_catalog.unnest(procedure.proargtypes::oid[]) with ordinality as arg(oid, ord)), '')
           ) as call_text,
           procedure.proname as name
    from pg_catalog.pg_proc as procedure
    join pg_catalog.pg_namespace as namespace on namespace.oid = procedure.pronamespace
    where namespace.nspname = 'public' and procedure.proname like 'social\_%'
    order by procedure.proname
  loop
    total := total + 1;
    begin
      execute 'select ' || fn.call_text;
      leaked := leaked || fn.name || ' ';
    exception when insufficient_privilege then
      denied := denied + 1;
    when others then
      leaked := leaked || fn.name || '(' || sqlstate || ') ';
    end;
